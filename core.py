def result_explanation(scores):
    """Explain a simple non-psychometric interest count, including close alternatives."""
    order=sorted(KEYS,key=lambda k:(-scores.get(k,0),KEYS.index(k)))
    leader,runner=order[:2]
    gap=scores.get(leader,0)-scores.get(runner,0)
    intro=f'🎯 <b>Основное направление:</b> {TRACKS[leader]}'
    if gap==0:
        if {leader,runner}=={'code','design'}:
            intro+='\n⚖️ <b>Смешанный профиль: Frontend-разработчик / UX-инженер.</b> Тебе интересны код и удобные интерфейсы.'
        else:
            intro+='\n⚖️ <b>Смешанный профиль:</b> несколько направлений набрали одинаковые максимальные баллы.'
    elif gap<=2:
        intro+='\n📌 <b>Результат смешанный:</b> разница между первыми направлениями небольшая. Исследуй оба.'
    intro+=f'\n🔎 <b>Близкая альтернатива:</b> {TRACKS[runner]} ({scores.get(runner,0)} из 7).'
    intro+='\n\nЭто подсчёт учебных интересов, а не стандартизированный психологический тест.'
    return intro

