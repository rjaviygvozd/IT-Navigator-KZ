TRACKS = {'code':'Разработка','data':'Аналитика и ИИ','people':'Управление IT','design':'UX/UI-дизайн'}
def tally(answers):
    if len(answers) != len(QUESTIONS) or any(a not in TRACKS for a in answers):
        raise ValueError('Expected exactly seven valid answers')
    return {key: answers.count(key) for key in TRACKS}
def leaders(scores):
    highest=max(scores.values())
    return [key for key in TRACKS if scores[key]==highest]
def describe(scores):
    winners=leaders(scores)
    if len(winners)==1:
        return 'Твой ведущий интерес: '+TRACKS[winners[0]]
    if set(winners)=={'code','design'}:
        return 'Смешанный профиль: разработка интерфейсов / UX-инженерия. Тебе интересны и код, и дизайн.'
    return 'Смешанный профиль: '+', '.join(TRACKS[k] for k in winners)+'. Исследуй несколько направлений.'
